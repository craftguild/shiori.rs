#!/usr/bin/env python3
"""Bind embedded dependency assets to the common distribution SBOM."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / '.craftguild/shipped-assets'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def copy(source, relative):
    destination = OUTPUT / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
    return destination.relative_to(ROOT).as_posix()


def main():
    metadata = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--locked', '--offline', '--format-version', '1'], cwd=ROOT))
    packages = {package['name']: package for package in metadata['packages']}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    records = []
    graphiql_package = packages['chigiri_graphiql']
    assert graphiql_package['source'].endswith('#5f90235ddb705a1a394b9a5cfda23a9ea62dc4b6')
    graphiql = Path(graphiql_package['manifest_path']).parent
    upstream = graphiql.parent.parent
    inventory = json.loads((graphiql / 'asset-inventory.json').read_text())
    for relative, expected in inventory['sources'].items():
        assert digest(upstream / relative) == expected, relative
    assert digest(graphiql / 'src/embedded.rs') == inventory['embedding']
    assert digest(graphiql / 'dependency-licenses.json') == inventory['licenses']
    actual = {p.relative_to(graphiql / 'assets').as_posix()
              for p in (graphiql / 'assets').rglob('*') if p.is_file()}
    assert actual == {entry['path'] for entry in inventory['files']}
    assets = []
    for entry in inventory['files']:
        source = graphiql / 'assets' / entry['path']
        assert source.stat().st_size == entry['bytes'] and digest(source) == entry['sha256']
        assets.append(copy(source, 'graphiql/assets/' + entry['path']))
    license_path = copy(graphiql / 'dependency-licenses.json', 'graphiql/dependency-licenses.json')
    copy(graphiql / 'asset-inventory.json', 'graphiql/asset-inventory.json')
    for package in json.loads((graphiql / 'dependency-licenses.json').read_text()):
        if package['bundled']:
            records.append({'name': package['name'], 'version': package['version'], 'type': 'library',
                'reference': f"urn:shiori:graphiql:{package['name']}:{package['version']}",
                'license': package['license'], 'files': [license_path, *assets],
                'evidence': 'The pinned Chigiri esbuild-derived inclusion record marks this package bundled. Shared GraphiQL output ownership is intentional; all asset bytes and upstream inventory/license hashes are verified.'})
    latex_package = packages['oriha-latex']
    assert latex_package['source'].endswith('#d46fa615fcd0e5d5ad730342436188ddb5a0e917')
    oriha = Path(latex_package['manifest_path']).parent.parent.parent
    for record in json.loads((oriha / 'assets/cli-supplemental.json').read_text()):
        record['reference'] = record['reference'].replace('urn:oriha:', 'urn:shiori:oriha:')
        record['files'] = [copy(oriha / name, 'oriha/' + name) for name in record['files']]
        records.append(record)
    for directory in ['crates/latex/assets/fonts', 'crates/core/entity-data', 'crates/core/emoji-data']:
        for source in (oriha / directory).rglob('*'):
            if source.is_file() and source.suffix in {'.txt', '.md'}:
                copy(source, 'oriha/' + source.relative_to(oriha).as_posix())
    banner = 'crates/shiori/banner.txt'
    records.append({'name': 'FIGlet Small Slant banner', 'version': '2.1-1996-layout', 'type': 'file',
        'reference': 'urn:shiori:banner', 'license': 'BSD-3-Clause', 'files': [banner, 'docs/notices/FIGlet-LICENSE'],
        'evidence': 'Committed ASCII artwork generated by the pinned Standards engine. The renderer and font are build tools; only the artwork is shipped.'})
    assert packages['libwebp-sys']['version'] == '0.9.6'
    webp = Path(packages['libwebp-sys']['manifest_path']).parent
    native_files = []
    for source in sorted(webp.rglob('*.h')):
        if source.name in {'encode.h', 'decode.h', 'types.h'}:
            native_files.append(copy(source, 'libwebp/' + source.relative_to(webp).as_posix()))
    assert native_files, 'Missing statically linked libwebp headers'
    records.append({'name': 'libwebp', 'version': '1.3.1', 'type': 'library',
        'reference': 'urn:shiori:native:libwebp', 'license': 'BSD-3-Clause',
        'files': [*native_files, 'docs/notices/libwebp-COPYING.txt', 'docs/notices/libwebp-PATENTS.txt'],
        'evidence': 'libwebp-sys 0.9.6 compiles its bundled libwebp 1.3.1 and sharpyuv into this executable; headers and original rights are retained. Rust image decoders are separately represented by the Cargo graph.'})
    (OUTPUT / 'supplemental.json').write_text(json.dumps(records, indent=2) + '\n')
    print(f'Verified {len(assets)} embedded GraphiQL assets; {len(records)} supplemental shipped components')


if __name__ == '__main__':
    main()
