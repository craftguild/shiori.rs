use super::*;
use oriha_core::RichTextProperties;
node!(InlineAnnotationResolver, Arc<Inline>, parent;
    annotation_kind: String => match &parent.content { RichTextProperties::Annotation { kind: value, .. } => value.clone(), _ => return Err(Error::Structure) };
    annotation_id: String => match &parent.content { RichTextProperties::Annotation { id: value, .. } => value.clone(), _ => return Err(Error::Structure) };
    classes: Vec<String> => match &parent.content { RichTextProperties::Annotation { classes: value, .. } => value.clone(), _ => return Err(Error::Structure) };
    data: Vec<Entry> => parent.data.clone();
);
